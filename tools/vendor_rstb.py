"""Writes docs/rstb-lib.js: ACNH RSTB Fixer's size-table code (same author, GPL-2.0) for the patcher page, unchanged.

    python tools/vendor_rstb.py [--fixer ../acnh-rstb-fixer] [--check]

It joins the fixer's lib/formats.js, lib/rstb.js and vendor/fzstd.umd.js (MIT) byte for byte inside one function, so
none of their names reach the page's globals, and exposes them as RSTB (browser) or module.exports (Node). --check
fails if docs/rstb-lib.js differs from what the fixer's current files give, so a rule change there is not missed.
"""
import argparse, sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / 'docs/rstb-lib.js'


def make(fixer: Path) -> str:
    read = lambda p: (fixer / p).read_text(encoding='utf-8').rstrip('\n')
    lic = '\n'.join(' * ' + l if l else ' *' for l in read('vendor/fzstd.LICENSE').splitlines())
    return f"""/* Generated by tools/vendor_rstb.py: do not edit. ACNH RSTB Fixer's size-table code (lib/formats.js, lib/rstb.js,
 * GPL-2.0, same author as this page) and fzstd (vendor/fzstd.umd.js), byte for byte. Rules: acnh-rstb-fixer README.
 * Their names stay inside the function below; the page gets one global, RSTB.
 *
 * fzstd's license:
{lic}
 */
(function () {{
const RSTB = {{}};
(function (self, module, exports, define, require) {{
// ---- lib/formats.js
{read('lib/formats.js')}
Object.assign(self, {{ readZip, read7z, crc32, writeZip, yaz0Raw, yaz0Dec, findBytes }});
// ---- lib/rstb.js
{read('lib/rstb.js')}
// ---- vendor/fzstd.umd.js
{read('vendor/fzstd.umd.js')}
}})(RSTB);
if (typeof module !== 'undefined') module.exports = RSTB; else globalThis.RSTB = RSTB;
}})();
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--fixer', default=str(REPO.parent / 'acnh-rstb-fixer'))
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    text = make(Path(a.fixer))
    if a.check:
        if OUT.read_text(encoding='utf-8') != text:
            sys.exit(f'{OUT.relative_to(REPO)} is not what {a.fixer} gives now: run python tools/vendor_rstb.py')
        print(f'{OUT.relative_to(REPO)} matches {a.fixer}')
        return
    OUT.write_text(text, encoding='utf-8', newline='\n')
    print(f'wrote {OUT.relative_to(REPO)} ({len(text.encode())} bytes)')


if __name__ == '__main__':
    main()
